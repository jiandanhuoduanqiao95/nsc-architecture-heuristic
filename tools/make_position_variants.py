#!/usr/bin/env python3
"""Generate (and verify) the M3 position-only variant modules for role B.

    python3 tools/make_position_variants.py            # (re)write variants/m3_beta_*.py
    python3 tools/make_position_variants.py --verify   # contract-check them

Each ``variants/m3_beta_<b>.py`` is a self-contained student module for the
matched attribution control M3 (TA 1/TA 2): the discount depends only on the
layer index, ``1/(1 + beta*(l+1)/L)``, through ctxnsc's primitives — never a
reimplementation. B runs the beta grid exactly like the alpha grid:

    python3 evaluate.py --split development --student variants/m3_beta_0.50.py

Same 5-value grid {0, 0.25, 0.5, 1, 2}, same selection rule and tie-break as
M2 (``tools/select_alpha.py --method position`` applies the frozen C4 rule).
Role A provides the entry points only; choosing beta* is role B's job.

``--verify`` checks, for every variant:
  (a) BETA equals the file's grid value;
  (b) score(config) is bitwise equal to
      ctxnsc.score_with_ratios(config, BETA, position_ratios(n_layer)) AND to
      an independently written fsum of A_l + F_l/(1 + BETA*(l+1)/L), on 10
      sampled archive configs;
  (c) ablation(config) == nsc.original_nsc(config) on all 200 configs;
  (d) BETA == 0: score == original_nsc bitwise on all 200 configs;
      BETA > 0: score < original_nsc on all 200 configs (every layer,
      including the first, is discounted by a position weight > 0);
  (e) if results/dev_m3_beta_<b>.json exists (an ``evaluate.py --student``
      run), its ``student`` ranking block equals the recomputation from
      direct scores, its ``ablation`` block equals the ``original_nsc`` block,
      and ``student`` differs from ``original_nsc`` iff BETA > 0.
No development correlation is printed: verification is not tuning.
"""
import argparse
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

import ctxnsc  # noqa: E402
import evaluate  # noqa: E402
import nsc  # noqa: E402
from tools.make_variants import load_module  # noqa: E402

GRID = (0.0, 0.25, 0.5, 1.0, 2.0)

M3_TEMPLATE = '''"""M3 position-only control at a fixed beta (generated, do not edit).

score(config)    -> sum_l [A_l + F_l / (1 + BETA * (l+1)/L)] via ctxnsc
                    (the discount depends on the layer index only).
ablation(config) -> the original NSC, independent of BETA.
Role B sweeps beta with evaluate.py --student; role C freezes beta* in
freeze.json. Generated by tools/make_position_variants.py.
"""
from nsc import original_nsc
from ctxnsc import score_with_ratios, position_ratios

BETA = {beta!r}


def score(config):
    """Return a finite scalar, with larger values predicting better quality."""
    return score_with_ratios(config, BETA, position_ratios(config["n_layer"]))


def ablation(config):
    """Disable the discount; the original NSC, independent of BETA."""
    return original_nsc(config)
'''


def variant_path(beta):
    return REPO / "variants" / f"m3_beta_{beta:.2f}.py"


def generate():
    (REPO / "variants").mkdir(exist_ok=True)
    for beta in GRID:
        path = variant_path(beta)
        path.write_text(M3_TEMPLATE.format(beta=beta), encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


def independent_m3(config, beta):
    """Independent formula (no ctxnsc): fsum of A_l + F_l / (1 + beta*(l+1)/L).

    The ratio is formed first, ``beta * ((i+1)/L)``, mirroring the
    primitive's association order so the bitwise comparison is valid for any
    beta (not only for the grid's exact powers of two).
    """
    d = config["d_model"]
    length = config["n_layer"]
    heads = config["n_head"] if isinstance(config["n_head"], list) else [config["n_head"]] * length
    inner = config["d_inner"] if isinstance(config["d_inner"], list) else [config["d_inner"]] * length
    return math.fsum(
        (3 * h * nsc.psi_mp(d, d // h) + nsc.psi_mp(d, d))
        + 2 * nsc.psi_mp(d, f) * (1.0 / (1.0 + beta * ((i + 1) / length)))
        for i, (h, f) in enumerate(zip(heads, inner)))


def ranking_block(scores, quality, pairs, matched):
    return {"spearman_rho": evaluate.correlation(evaluate.ranks(scores),
                                                 evaluate.ranks(quality)),
            "all_pairs": evaluate.pair_summary(scores, quality, pairs),
            "size_controlled_pairs": evaluate.pair_summary(scores, quality, matched)}


def verify():
    configs = json.loads((REPO / "data" / "architectures.json").read_text())
    keys_all = sorted(configs)
    sampled = keys_all[::20][:10]
    failures = []
    dev = None
    for beta in GRID:
        path = variant_path(beta)
        name = path.name
        if not path.exists():
            failures.append(f"{name}: missing (run tools/make_position_variants.py)")
            continue
        module = load_module(path)
        if getattr(module, "BETA", None) != beta:
            failures.append(f"{name}: BETA {getattr(module, 'BETA', None)!r} != {beta!r}")
            continue
        for key in sampled:
            cfg = configs[key]
            got = module.score(cfg)
            primitive = ctxnsc.score_with_ratios(cfg, beta,
                                                 ctxnsc.position_ratios(cfg["n_layer"]))
            if got != primitive or got != independent_m3(cfg, beta):
                failures.append(f"{name}: score({key}) not bitwise equal to the "
                                f"primitive / independent formula")
        for key in keys_all:
            cfg = configs[key]
            s0 = nsc.original_nsc(cfg)
            if module.ablation(cfg) != s0:
                failures.append(f"{name}: ablation({key}) != original_nsc")
            score = module.score(cfg)
            if beta == 0.0 and score != s0:
                failures.append(f"{name}: BETA=0 score({key}) != original_nsc")
            if beta > 0.0 and not score < s0:
                failures.append(f"{name}: BETA>0 score({key}) not < original_nsc")
        evaluated = REPO / "results" / f"dev_m3_beta_{beta:.2f}.json"
        if evaluated.exists():
            if dev is None:
                dev = load_dev(configs)
            keys, quality, pairs, matched = dev
            payload = json.loads(evaluated.read_text())
            scores = [evaluate.canonical(module.score(configs[k])) for k in keys]
            ranking = payload["ranking"]
            if ranking["student"] != ranking_block(scores, quality, pairs, matched):
                failures.append(f"{name}: {evaluated.name} student block != "
                                f"recomputation from direct scores")
            if ranking["ablation"] != ranking["original_nsc"]:
                failures.append(f"{name}: {evaluated.name} ablation block != "
                                f"original_nsc block")
            same = ranking["student"] == ranking["original_nsc"]
            if (beta == 0.0) != same:
                failures.append(f"{name}: {evaluated.name} student vs original_nsc "
                                f"equality ({same}) contradicts BETA={beta}")
            print(f"OK   {name}: scores bitwise (primitive + independent formula); "
                  f"ablation == original_nsc; {evaluated.name}: student block "
                  f"matches recomputation, ablation == original_nsc, student "
                  f"{'==' if same else '!='} original_nsc")
        elif not any(f.startswith(name) for f in failures):
            print(f"OK   {name}: scores bitwise (primitive + independent formula); "
                  f"ablation == original_nsc on 200; "
                  f"{'score == original_nsc on 200' if beta == 0.0 else 'score < original_nsc on 200'}"
                  f" (no results/{evaluated.name} to cross-check)")
    if failures:
        for line in failures[:20]:
            print("FAIL", line)
        print(f"{len(failures)} verification failures")
        return 1
    print("M3 VARIANTS OK")
    return 0


def load_dev(configs):
    splits = json.loads((REPO / "data" / "splits.json").read_text())
    labels = json.loads((REPO / "data" / "development_labels.json").read_text())
    resources = json.loads((REPO / "data" / "resources.json").read_text())
    keys = splits["development"]
    quality = [-labels[k]["valid_ppl"] for k in keys]
    total = [resources[k]["total"] for k in keys]
    pairs = [(i, j) for i in range(len(keys)) for j in range(i)]
    matched = [(i, j) for i, j in pairs
               if configs[keys[i]]["d_model"] == configs[keys[j]]["d_model"]
               and min(total[i], total[j]) / max(total[i], total[j]) >= 0.90]
    return keys, quality, pairs, matched


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify", action="store_true",
                        help="verify existing variants instead of writing them")
    args = parser.parse_args()
    return verify() if args.verify else generate()


if __name__ == "__main__":
    sys.exit(main())
